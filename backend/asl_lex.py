"""ASL-LEX 2.0: a dictionary of 2,723 ASL signs (Sehyr, Caselli, Cohen-Goldberg & Emmorey, 2021). CC BY-NC 4.0.

    python -m backend.asl_lex import "path/to/Data Files/signdata.csv"

writes shared/asl_lex.json (a trimmed copy) and shared/next_signs.md (child-vocabulary signs we have no
clip for yet, earliest-learned first). At runtime, has_sign(word) says whether a real sign exists for a
word the app had to fingerspell, so it can be animated next.
"""
import csv
import json
import re
import sys
from pathlib import Path

SHARED = Path(__file__).parent.parent / "shared"
LEX = SHARED / "asl_lex.json"
NEXT = SHARED / "next_signs.md"
CREDIT = ("ASL-LEX 2.0, Sehyr, Caselli, Cohen-Goldberg & Emmorey (2021), https://asl-lex.org, "
          "licensed CC BY-NC 4.0")


def _num(v):
    try:
        return round(float(v), 2)
    except (TypeError, ValueError):
        return None


def _words(text):
    return [w.strip().lower() for w in re.split(r"[,;/]", text or "") if w.strip()]


def import_csv(csv_path):
    """signdata.csv -> list of trimmed entries."""
    with open(csv_path, encoding="utf-8-sig", errors="replace", newline="") as f:
        rows = list(csv.DictReader(f))
    entries = []
    for r in rows:
        lemma = re.sub(r"_\d+$", "", r["LemmaID"]).replace("_", " ").lower()
        english = list(dict.fromkeys([lemma, *_words(r["DominantTranslation"]), *_words(r["NondominantTranslations"])]))
        entries.append({
            "entry": r["EntryID"],
            "english": english,
            "frequency": _num(r["SignFrequency(M)"]),        # 1 (rare) to 7 (very common), rated by deaf signers
            "iconicity": _num(r["Iconicity(M)"]),            # 1 to 7: how much the sign looks like its meaning
            "child_vocab": r["InCDI"] == "Yes",              # on the ASL Communicative Development Inventory
            "child_category": r["CDISemanticCategory"] or None,
            "age_learned_months": _num(r["bglm_aoa"]),       # estimated age children learn it
            "handshape": r["Handshape.2.0"] or None,
            "location": " / ".join(x for x in (r["MajorLocation.2.0"], r["MinorLocation.2.0"]) if x) or None,
        })
    return entries


def write_files(entries, vocab, lex_path=LEX, next_path=NEXT):
    lex_path.write_text(json.dumps({"credit": CREDIT, "signs": entries}, ensure_ascii=False, indent=0) + "\n",
                        encoding="utf-8")
    have = {v.get("asl_lex") for v in vocab}
    todo = [e for e in entries if e["child_vocab"] and e["entry"] not in have]
    todo.sort(key=lambda e: (e["age_learned_months"] or 99, -(e["frequency"] or 0)))
    lines = ["# Next signs to animate", "",
             "Signs from the ASL children's vocabulary checklist that `shared/vocab.json` doesn't have yet, "
             "earliest-learned first. Generated by `python -m backend.asl_lex import`; don't edit by hand.", "",
             f"Source: {CREDIT}.", "",
             "| Sign | English | Category | Learned at (months) | How common (1-7) | Handshape | Location |",
             "|---|---|---|---|---|---|---|"]
    for e in todo:
        lines.append(f"| {e['entry']} | {', '.join(e['english'][:3])} | {e['child_category'] or ''} | "
                     f"{e['age_learned_months'] or ''} | {e['frequency'] or ''} | {e['handshape'] or ''} | {e['location'] or ''} |")
    next_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(todo)


def load(path=LEX):
    if not path.exists():
        return {}
    index = {}
    for e in json.loads(path.read_text(encoding="utf-8"))["signs"]:
        for w in e["english"]:
            index.setdefault(w, e)  # first entry wins, so eat_1 beats eat_2
    return index


INDEX = load()


def has_sign(word, index=None):
    """ASL-LEX entry id when a real sign exists for this English word, else None."""
    e = (INDEX if index is None else index).get(word.lower())
    return e["entry"] if e else None


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] != "import":
        sys.exit('usage: python -m backend.asl_lex import "path/to/Data Files/signdata.csv"')
    vocab = json.loads((SHARED / "vocab.json").read_text(encoding="utf-8"))
    entries = import_csv(sys.argv[2])
    todo = write_files(entries, vocab)
    known = {e["entry"] for e in entries}
    missing = [v["gloss"] for v in vocab if v.get("asl_lex") not in known]
    print(f"{len(entries)} signs -> {LEX.name}; {todo} child-vocabulary signs listed in {NEXT.name}")
    if missing:
        print("vocab.json signs with no ASL-LEX match:", ", ".join(missing))
